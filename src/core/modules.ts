export interface ModuleOverrides {
  /** Field lists you've edited, by app id. */
  fields?: Record<string, FieldDef[]>;
}

export function applyOverrides(defaults: ModuleDef[], o: ModuleOverrides | null): ModuleDef[] {
  if (!o?.fields) return defaults;
  return defaults.map((m) => (o.fields![m.id] ? { ...m, fields: o.fields![m.id] } : m));
}
